import { afterEach, expect, test } from "bun:test";
import { createMockServices, type MockRuntime } from "../../infrastructure/browser/mock/create-mock-services";
import { MemoryPersistence } from "../../infrastructure/browser/mock/store";
import { seedFoundation } from "../../infrastructure/browser/mock/scenarios/foundation";
import { unwrap, type Result } from "../../presentation/framework/services/contracts";

const scope = { orgId: "org_north", projectId: "project_north_notes", environmentId: "env_north_notes_development" }, context = { scope };
const realmId = `realm_${scope.environmentId}`, administrative = { mode: "administrative" as const };
let runtime: MockRuntime;
const options = (revision?: string) => ({ idempotencyKey: crypto.randomUUID(), expectedRevision: revision });
const code = (result: Result<unknown>) => result.ok ? undefined : result.error.code;
async function setup() {
  const persistence = new MemoryPersistence(seedFoundation(1000));
  runtime = createMockServices({ persistence, wallTime: () => 1000, autoTick: false });
  unwrap(await runtime.tools.setLatency(0)); unwrap(await runtime.tools.selectIdentity("owner"));
  unwrap(await runtime.services.platform.command(context, { kind: "provision", services: ["auth"] }, options("r1"))); unwrap(await runtime.tools.setClock(true, 5000)); return { ...runtime.services, persistence };
}
afterEach(() => runtime?.dispose());

test("app proof is one-use and realm/session policy never grants dashboard authority", async () => {
  const { appAuth, data, session } = await setup();
  const table = unwrap(await data.listTables(context)).items[0];
  const alice = unwrap(await appAuth.listUsers(context, { email: "alice" })).items[0], bob = unwrap(await appAuth.listUsers(context, { email: "bob" })).items[0];
  expect(unwrap(await appAuth.queryRows(realmId, table.id, {})).total).toBe(0);
  unwrap(await appAuth.requestChallenge(realmId, { email: alice.email, provider: "email", redirect: "http://localhost:3000/callback" }, options()));
  const proof = unwrap(await appAuth.inbox(context)).items[0].id;
  unwrap(await appAuth.consumeChallenge(realmId, proof));
  const appSession = unwrap(await appAuth.currentSession(realmId))!;
  expect(code(await appAuth.consumeChallenge(realmId, proof))).toBe("forbidden");
  expect(unwrap(await appAuth.currentSession(realmId))!.session.id).toBe(appSession.session.id);
  expect(unwrap(await session.getSession())!.accountId).toBe("owner");
  const rows = unwrap(await appAuth.queryRows(realmId, table.id, {})); expect(rows.total).toBe(1);
  expect(code(await appAuth.rowCommand(realmId, table.id, { kind: "update", rowId: rows.items[0].id, values: { owner_id: bob.id } }, options(rows.items[0].revision)))).toBe("forbidden");
  expect(code(await appAuth.sessionCommand(realmId, "profile", { roles: ["admin"] }))).toBe("validation");
  unwrap(await appAuth.rowCommand(realmId, table.id, { kind: "insert", values: { owner_id: alice.id, title: "Mine", document: { count: 3, done: false } } }, options()));
  expect(unwrap(await appAuth.queryRows(realmId, table.id, {})).total).toBe(2);
  const current = unwrap(await appAuth.getUser(context, alice.id)).user;
  unwrap(await appAuth.userCommand(context, { kind: "suspend", userId: alice.id }, "", options(current.revision)));
  expect(unwrap(await appAuth.currentSession(realmId))).toBeNull();
  expect(code(await appAuth.sessionCommand(realmId, "rotate"))).toBe("unauthenticated");
  expect(unwrap(await data.queryRows(context, table.id, {}, administrative)).total).toBe(3);
  unwrap(await runtime.tools.selectIdentity("developer"));
  expect(unwrap(await data.getTable(context, table.id)).id).toBe(table.id);
  expect(code(await data.queryRows(context, table.id, {}, administrative))).toBe("forbidden");
  expect(code(await appAuth.listUsers(context))).toBe("forbidden");
  expect(code(await data.getTable({ scope: { orgId: "org_south", projectId: "project_south_notes", environmentId: "env_south_notes_development" } }, table.id))).toBe("not_found");
});

test("schema and rows share transactional constraints, revisions, imports and generated types", async () => {
  const { data, persistence } = await setup();
  const created = unwrap(await data.schemaCommand(context, { kind: "create", name: "counts", columns: [{ name: "id", type: "integer", nullable: false }, { name: "count", type: "integer", nullable: false }, { name: "doc", type: "jsonb", nullable: true }], primaryKey: "id", rls: true, policies: [] }, "", options()));
  const id = created.resourceId!;
  unwrap(await data.rowCommand(context, id, { kind: "insert", values: { id: 1, count: 2, doc: { done: false } } }, administrative, "", options()));
  const row = unwrap(await data.queryRows(context, id, {}, administrative)).items[0];
  unwrap(await data.rowCommand(context, id, { kind: "update", rowId: row.id, values: { count: 3 } }, administrative, "", options(row.revision)));
  expect(code(await data.rowCommand(context, id, { kind: "update", rowId: row.id, values: { count: 4 } }, administrative, "", options(row.revision)))).toBe("conflict");
  expect(code(await data.rowCommand(context, id, { kind: "insert", values: { id: 1, count: 5 } }, administrative, "", options()))).toBe("conflict");
  const dependent = unwrap(await data.schemaCommand(context, { kind: "create", name: "references", columns: [{ name: "id", type: "integer", nullable: false }, { name: "count_id", type: "integer", nullable: false }], primaryKey: "id", rls: true, policies: [] }, "", options())).resourceId!;
  unwrap(await data.schemaCommand(context, { kind: "constraint", tableId: dependent, constraint: { id: "count_fk", name: "count_fk", kind: "foreign-key", columns: ["count_id"], targetTableId: id, targetColumn: "id" } }, "", options("r1")));
  unwrap(await data.rowCommand(context, dependent, { kind: "insert", values: { id: 1, count_id: 1 } }, administrative, "", options()));
  const protectedRow = unwrap(await data.queryRows(context, id, {}, administrative)).items[0];
  expect(code(await data.rowCommand(context, id, { kind: "delete", rows: [{ id: protectedRow.id, revision: protectedRow.revision }], confirmation: "1" }, administrative, "", options()))).toBe("conflict");
  expect(unwrap(await data.queryRows(context, id, {}, administrative)).total).toBe(1);
  const table = unwrap(await data.getTable(context, id));
  const input = { format: "csv" as const, text: 'source,count\n2,4\n3,wrong\n4,6', mapping: { source: "id" }, conflict: "error" as const, atomic: false };
  expect(unwrap(await data.previewImport(context, id, input)).errors).toHaveLength(1);
  const imported = unwrap(await data.importRows(context, id, input, "", options(table.revision)));
  unwrap(await runtime.tools.setClock(true, 3000));
  expect(unwrap(await data.getJobResult(context, imported.operationId!)).errors).toHaveLength(1);
  expect(unwrap(await data.queryRows(context, id, {}, administrative)).total).toBe(3);
  const latest = unwrap(await data.getTable(context, id));
  unwrap(await data.schemaCommand(context, { kind: "column", tableId: id, column: { name: "active", type: "boolean", nullable: false, default: { kind: "literal", value: true } } }, "", options(latest.revision)));
  expect(unwrap(await data.queryRows(context, id, {}, administrative)).items.every(r => r.values.active === true)).toBe(true);
  expect(unwrap(await data.generatedTypes(context, id)).text).toContain("active: boolean");
  runtime.dispose(); runtime = createMockServices({ persistence, wallTime: () => 1000, autoTick: false });
  expect(unwrap(await runtime.services.data.queryRows(context, id, {}, administrative)).total).toBe(3);
});

test("SQL is bounded and cancellable; exports and job replay recheck revoked access", async () => {
  const { data, appAuth } = await setup();
  const table = unwrap(await data.listTables(context)).items[0];
  expect(code(await data.executeSql(context, "DROP DATABASE carbon;", administrative, "", options()))).toBe("unsupported_operation");
  const cancelled = unwrap(await data.executeSql(context, "SELECT * FROM notes;", administrative, "", options()));
  const op = unwrap(await runtime.services.operations.get(context, cancelled.operationId!));
  unwrap(await data.cancelJob(context, op.id, options(op.revision))); unwrap(await runtime.tools.setClock(true, 3000));
  expect(unwrap(await runtime.services.operations.get(context, op.id)).state).toBe("cancelled");
  const run = unwrap(await data.executeSql(context, "SELECT * FROM notes LIMIT 1;", administrative, "", options()));
  unwrap(await runtime.tools.setClock(true, 3000));
  expect(unwrap(await data.sqlResult(context, run.resourceId!)).rows).toHaveLength(1);
  const alice = unwrap(await appAuth.listUsers(context, { email: "alice" })).items[0];
  const exported = unwrap(await data.exportRows(context, table.id, { columns: ["title"] }, { mode: "policy-preview", userId: alice.id }, options()));
  unwrap(await runtime.tools.setClock(true, 3000));
  expect(unwrap(await data.getJobResult(context, exported.operationId!)).download!.text).toContain("Alice");
  const latest = unwrap(await data.getTable(context, table.id));
  unwrap(await data.schemaCommand(context, { kind: "policies", tableId: table.id, rls: true, policies: [] }, "", options(latest.revision)));
  expect(code(await data.getJobResult(context, exported.operationId!))).toBe("forbidden");
  unwrap(await runtime.tools.selectIdentity("viewer"));
  expect(code(await data.sqlResult(context, run.resourceId!))).toBe("forbidden");
  expect(code(await data.getJobResult(context, exported.operationId!))).toBe("forbidden");
  unwrap(await runtime.tools.selectIdentity("owner"));
  const productionScope = { ...scope, environmentId: "env_north_notes_production" };
  expect(code(await data.schemaCommand({ scope: productionScope }, { kind: "create", name: "blocked", columns: [{ name: "id", type: "integer", nullable: false }], primaryKey: "id", rls: true, policies: [] }, "", options()))).toBe("validation");
  const replayOptions = options();
  unwrap(await runtime.tools.selectIdentity("developer"));
  const payload = { name: "Saved receipt", text: "SELECT * FROM notes", shared: false };
  unwrap(await data.saveQuery(context, payload, replayOptions));
  unwrap(await runtime.tools.revokeMembership(scope));
  expect(code(await data.saveQuery(context, payload, replayOptions))).toBe("not_found");
});
