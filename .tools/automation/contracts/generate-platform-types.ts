// This deliberately supports only the schema constructs used by this contract.
// Runtime constraints (patterns, format, oneOf) remain enforced by Ajv.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../../", import.meta.url);
const schema = JSON.parse(readFileSync(new URL("solutions/contracts/platform/schema/platform.schema.json", root), "utf8"));
type Schema = Record<string, any>;
function type(s: Schema): string {
  if (s.$ref) return s.$ref.replace("#/$defs/", "");
  if ("const" in s) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v: unknown) => JSON.stringify(v)).join(" | ");
  if (s.anyOf) return s.anyOf.map(type).join(" | ");
  switch (s.type) {
    case "string": return "string";
    case "integer": case "number": return "number";
    case "boolean": return "boolean";
    case "null": return "null";
    case "array": return `ReadonlyArray<${type(s.items)}>`;
    case "object": {
      const fields = Object.entries<Schema>(s.properties ?? {}).map(([k, v]) => `readonly ${JSON.stringify(k)}${s.required?.includes(k) ? "" : "?"}: ${type(v)};`);
      if (s.additionalProperties && typeof s.additionalProperties === "object") fields.push(`readonly [key: string]: ${type(s.additionalProperties)};`);
      return `{ ${fields.join(" ")} }`;
    }
    default:
      if (Object.keys(s).length === 0) return "unknown";
      throw new Error(`Unsupported TypeScript schema: ${JSON.stringify(s)}`);
  }
}
const output = "// Generated by .tools/automation/contracts/generate-platform-types.ts. Do not edit.\n\n"
  + Object.entries<Schema>(schema.$defs).map(([name, s]) => `export type ${name} = ${type(s)};`).join("\n\n")
  + "\n\nexport interface Components {\n" + Object.keys(schema.$defs).map(name => `  ${name}: ${name};`).join("\n") + "\n}\n";
const target = new URL("solutions/contracts/platform/types/Platform.ts", root);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) throw new Error("Platform types drifted; run bun .tools/automation/contracts/generate-platform-types.ts");
} else writeFileSync(target, output);
